function createBlogStore() {
	const { subscribe, set, update } = writable<BlogPost[]>(samplePosts);

	return {
		subscribe,
		getBySlug: (slug: string): BlogPost | undefined => {
			let found: BlogPost | undefined;
			samplePosts.forEach((post) => {
				if (post.slug === slug) found = post;
			});
			return found;
		},
		getByCategory: (category: string): BlogPost[] => {
			return samplePosts.filter((post) => post.category === category);
		},
		getByTag: (tag: string): BlogPost[] => {
			return samplePosts.filter((post) => post.tags.includes(tag));
		},
		getRecent: (limit: number = 5): BlogPost[] => {
			return [...samplePosts]
				.sort((a, b) => new Date(b.publishedDate).getTime() - new Date(a.publishedDate).getTime())
				.slice(0, limit);
		}
	};
}

export const blogStore = createBlogStore();
